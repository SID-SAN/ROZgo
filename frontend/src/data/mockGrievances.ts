import { Grievance, UserRole } from '../types';

export interface GrievanceCategoryMeta {
  id: string;
  labelKey: string;
  defaultLabel: string;
  workerLabel?: string;
  employerLabel?: string;
  iconName: string;
  description: string;
  workerDescription?: string;
  employerDescription?: string;
  relevantRoles: UserRole[]; // 'worker', 'employer', or both
  isSafety?: boolean;
}

export const getCategoryDisplay = (cat: GrievanceCategoryMeta, role: UserRole) => {
  const isWorker = role === 'worker';
  return {
    label: (isWorker ? cat.workerLabel : cat.employerLabel) || cat.defaultLabel,
    description: (isWorker ? cat.workerDescription : cat.employerDescription) || cat.description,
  };
};

